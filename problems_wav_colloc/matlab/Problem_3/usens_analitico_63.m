function u = usens_analitico_63(cA, cB, V, k1, k2, cBin)
% Expressao fechada de u_sens para o Exemplo 6.3 (Srinivasan et al., 2003).
%
% NOTA: a Eq. (71) do artigo original saiu corrompida na conversao OCR
% do PDF fornecido (sinais e expoentes ilegiveis). Em vez de arriscar
% uma transcricao errada, esta expressao foi RE-DERIVADA simbolicamente
% (Python/sympy) a partir da condicao de singularidade det(M)=0, com
% M = [Fu, DFu, D2Fu] (matriz 3x3, estado x=(cA,cB,V), seguindo a
% definicao do operador D da Eq. 19 do artigo). A raiz fisicamente
% relevante (a que fica dentro de [umin,umax] e bate com a solucao
% numerica) foi escolhida e validada contra a colocacao Haar
% (erro medio ~7e-5 num u que varia em ~1e-3, com regularizacao
% adequada -- ver myfun_reactor63_haar.m).
%
% Uso: u = usens_analitico_63(cA, cB, V, k1, k2, cBin)  (aceita vetores)

    num = cA.^2.*k1.^2 + 6*cA.*cB.*k1.*k2 + cA.*cBin.*k1.^2 - cB.^2.*k1.^2 ...
        - 2*cB.^2.*k1.*k2 + 8*cB.^2.*k2.^2 + cB.*cBin.*k1.^2 + cB.*cBin.*k1.*k2 ...
        + sqrt(cA.^4.*k1.^4 + 12*cA.^3.*cB.*k1.^3.*k2 + 2*cA.^3.*cBin.*k1.^4 ...
        - 2*cA.^2.*cB.^2.*k1.^4 - 12*cA.^2.*cB.^2.*k1.^3.*k2 + 52*cA.^2.*cB.^2.*k1.^2.*k2.^2 ...
        + 2*cA.^2.*cB.*cBin.*k1.^4 + 18*cA.^2.*cB.*cBin.*k1.^3.*k2 + cA.^2.*cBin.^2.*k1.^4 ...
        + 4*cA.*cB.^3.*k1.^3.*k2 - 56*cA.*cB.^3.*k1.^2.*k2.^2 + 96*cA.*cB.^3.*k1.*k2.^3 ...
        - 2*cA.*cB.^2.*cBin.*k1.^4 - 8*cA.*cB.^2.*cBin.*k1.^3.*k2 + 52*cA.*cB.^2.*cBin.*k1.^2.*k2.^2 ...
        + 2*cA.*cB.*cBin.^2.*k1.^4 + 6*cA.*cB.*cBin.^2.*k1.^3.*k2 + cB.^4.*k1.^4 ...
        - 4*cB.^4.*k1.^3.*k2 + 20*cB.^4.*k1.^2.*k2.^2 - 64*cB.^4.*k1.*k2.^3 + 64*cB.^4.*k2.^4 ...
        - 2*cB.^3.*cBin.*k1.^4 + 6*cB.^3.*cBin.*k1.^3.*k2 - 28*cB.^3.*cBin.*k1.^2.*k2.^2 ...
        + 48*cB.^3.*cBin.*k1.*k2.^3 + cB.^2.*cBin.^2.*k1.^4 - 2*cB.^2.*cBin.^2.*k1.^3.*k2 ...
        + 9*cB.^2.*cBin.^2.*k1.^2.*k2.^2);

    den = 2*(-2*cA.*cB.*k1 + cA.*cBin.*k1 + 2*cB.^2.*k1 - 4*cB.^2.*k2 ...
        - 3*cB.*cBin.*k1 + 4*cB.*cBin.*k2 + cBin.^2.*k1);

    u = V.*cB.*num ./ den;

end
